`timescale 1ns / 1ps

module tb_dual_precision_mac;

    // Inputs
    reg        clk;
    reg        rst;

    reg [7:0]  A;
    reg [7:0]  B;
    reg [7:0]  C;

    reg [1:0]  mode;

    // Output
    wire [7:0] result;


    // =====================================================
    // DUT
    // =====================================================

    dual_precision_mac uut (

        .clk(clk),
        .rst(rst),

        .A(A),
        .B(B),
        .C(C),

        .mode(mode),

        .result(result)
    );


    // =====================================================
    // Clock Generation
    // =====================================================

    initial begin
        clk = 1'b0;

        forever #5 clk = ~clk;
    end


    // =====================================================
    // Test Cases
    // =====================================================

    initial begin

        // -------------------------------------------------
        // RESET
        // -------------------------------------------------

        rst  = 1'b1;

        A    = 8'b00000000;
        B    = 8'b00000000;
        C    = 8'b00000000;

        mode = 2'b00;

        #20;

        rst = 1'b0;


        // =================================================
        // TEST 1: FP8 E4M3
        // =================================================

        mode = 2'b00;

        // A = 1.5
        A = 8'b00111100;

        // B = 1.5
        B = 8'b00111100;

        // C = 1.0
        C = 8'b00111000;

        #20;

        $display("--------------------------------------");
        $display("TEST 1 : FP8 E4M3");
        $display("A      = %b", A);
        $display("B      = %b", B);
        $display("C      = %b", C);
        $display("Result = %b", result);


        // =================================================
        // TEST 2: FP8 E5M2
        // =================================================

        mode = 2'b01;

        // A = 1.5
        A = 8'b00111110;

        // B = 1.5
        B = 8'b00111110;

        // C = 1.0
        C = 8'b00111100;

        #20;

        $display("--------------------------------------");
        $display("TEST 2 : FP8 E5M2");
        $display("A      = %b", A);
        $display("B      = %b", B);
        $display("C      = %b", C);
        $display("Result = %b", result);


        // =================================================
        // TEST 3: FP4 E2M1
        // =================================================

        mode = 2'b10;

        A = 8'b00000101;
        B = 8'b00000101;
        C = 8'b00000100;

        #20;

        $display("--------------------------------------");
        $display("TEST 3 : FP4 E2M1");
        $display("A      = %b", A);
        $display("B      = %b", B);
        $display("C      = %b", C);
        $display("Result = %b", result);


        // =================================================
        // TEST 4: FP4 E1M2
        // =================================================

        mode = 2'b11;

        A = 8'b00000110;
        B = 8'b00000110;
        C = 8'b00000101;

        #20;

        $display("--------------------------------------");
        $display("TEST 4 : FP4 E1M2");
        $display("A      = %b", A);
        $display("B      = %b", B);
        $display("C      = %b", C);
        $display("Result = %b", result);


        // =================================================
        // TEST 5: ReLU
        // =================================================

        mode = 2'b00;

        // Negative 1.5
        A = 8'b10111100;

        // Positive 1.5
        B = 8'b00111100;

        // C = 0
        C = 8'b00000000;

        #20;

        $display("--------------------------------------");
        $display("TEST 5 : ReLU");
        $display("A      = %b", A);
        $display("B      = %b", B);
        $display("C      = %b", C);
        $display("Result = %b", result);


        #20;

        $display("--------------------------------------");
        $display("SIMULATION COMPLETED");

        $finish;

    end

endmodule